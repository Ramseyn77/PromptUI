// Generates data/registry-sources.ts from components/registry/*.tsx so the code shown
// on the site is always the exact file rendered in the preview. Runs before dev and build.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const registryDir = join(root, 'components', 'registry');
const outFile = join(root, 'data', 'registry-sources.ts');

const toSlug = (fileName) => fileName.replace(/\.tsx$/, '').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const entries = readdirSync(registryDir)
  .filter((file) => file.endsWith('.tsx'))
  .sort()
  .map((file) => {
    const source = readFileSync(join(registryDir, file), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    return `  ${JSON.stringify(toSlug(file))}: ${JSON.stringify(source)},`;
  });

const output = `// Generated by scripts/sync-registry.mjs from components/registry. Do not edit by hand.\nexport const registrySources: Record<string, string> = {\n${entries.join('\n')}\n};\n`;

let previous = '';
try { previous = readFileSync(outFile, 'utf8'); } catch {}
if (previous !== output) writeFileSync(outFile, output);
console.log(`registry: ${entries.length} component sources synced`);
