// Builds the component registry from components/registry/<category>/<Name>.tsx.
// Each file starts with an @registry header (name, category, style, description, prompt, tags)
// and exports a function named like the file. This script generates:
//   - components/registry/index.ts   slug -> component, for the previews
//   - data/registry-generated.ts     metadata + displayed source (header stripped)
// It runs before `dev` and `build`, and fails loudly on invalid files.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const registryDir = join(root, 'components', 'registry');
const indexFile = join(registryDir, 'index.ts');
const dataFile = join(root, 'data', 'registry-generated.ts');

const categories = ['Hero', 'Navbar', 'Cards', 'Buttons', 'Checkboxes', 'AI Chat', 'Forms', 'Pricing', 'Testimonials', 'Dashboard', 'Tables', 'Boards', 'Charts', 'Shaders', 'Footer', 'CTA', 'Loader', 'Menu', 'Toggle', 'Tooltips', 'Text', 'Sidebar'];
const styles = ['Minimal', 'Gradient', 'Glass', 'Dark', 'Editorial', 'SaaS'];
const legacySlugs = new Set([...readFileSync(join(root, 'data', 'components.ts'), 'utf8').matchAll(/slug: '([^']+)'/g)].map((match) => match[1]));

const toSlug = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase();

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) return walk(path);
    return path.endsWith('.tsx') ? [path] : [];
  });
}

const errors = [];
const seen = new Map();
const entries = walk(registryDir).sort().map((path) => {
  const file = relative(registryDir, path).split(sep).join('/');
  const exportName = path.split(sep).pop().replace(/\.tsx$/, '');
  const slug = toSlug(exportName);
  const raw = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  const header = raw.match(/^\/\*\*\n \* @registry\n([\s\S]*?)\n \*\/\n+/);
  if (!header) { errors.push(`${file}: missing @registry header`); return null; }

  const meta = Object.fromEntries(header[1].split('\n').map((line) => line.replace(/^ \* ?/, '')).filter(Boolean).map((line) => {
    const index = line.indexOf(':');
    return [line.slice(0, index).trim(), line.slice(index + 1).trim()];
  }));
  const code = raw.slice(header[0].length).trimEnd();

  if (!categories.includes(meta.category)) errors.push(`${file}: unknown category "${meta.category}"`);
  if (!styles.includes(meta.style)) errors.push(`${file}: unknown style "${meta.style}"`);
  for (const key of ['name', 'description', 'prompt']) if (!meta[key]) errors.push(`${file}: missing ${key}`);
  if (!new RegExp(`export function ${exportName}\\(`).test(code)) errors.push(`${file}: must export function ${exportName}()`);
  if (legacySlugs.has(slug)) errors.push(`${file}: slug "${slug}" already used by a legacy component`);
  if (seen.has(slug)) errors.push(`${file}: slug "${slug}" duplicates ${seen.get(slug)}`);
  seen.set(slug, file);

  const tags = (meta.tags ?? '').split(',').map((tag) => tag.trim());
  const technologies = ['React', 'TypeScript', 'Tailwind', ...(code.includes("from 'lucide-react'") ? ['Lucide'] : [])];
  return { file, exportName, slug, code, technologies, featured: tags.includes('featured'), recent: tags.includes('recent'), ...meta };
}).filter(Boolean);

if (errors.length) {
  console.error(`registry: ${errors.length} error(s)\n  - ${errors.join('\n  - ')}`);
  process.exit(1);
}

const write = (path, content) => {
  let previous = '';
  try { previous = readFileSync(path, 'utf8'); } catch {}
  if (previous !== content) writeFileSync(path, content);
};

write(indexFile, [
  '// Generated by scripts/sync-registry.mjs. Do not edit by hand.',
  "import type { ComponentType } from 'react';",
  ...entries.map((entry) => `import { ${entry.exportName} } from './${entry.file.replace(/\.tsx$/, '')}';`),
  '',
  '/** Registry components render from their own file and support light and dark mode. */',
  'export const registryComponents: Record<string, ComponentType> = {',
  ...entries.map((entry) => `  ${JSON.stringify(entry.slug)}: ${entry.exportName},`),
  '};',
  '',
].join('\n'));

const fields = ['slug', 'name', 'category', 'style', 'description', 'prompt', 'technologies', 'featured', 'recent', 'code'];
write(dataFile, [
  '// Generated by scripts/sync-registry.mjs from components/registry. Do not edit by hand.',
  "import type { LibraryComponent } from '@/types/component';",
  '',
  "export const registryEntries: Omit<LibraryComponent, 'responsiveModes' | 'safetyNotes'>[] = [",
  ...entries.map((entry) => `  { ${fields.map((key) => `${key}: ${JSON.stringify(entry[key])}`).join(', ')}, responsive: true },`),
  '];',
  '',
].join('\n'));

const perCategory = categories.map((category) => `${category} ${entries.filter((entry) => entry.category === category).length}`).join(' | ');
console.log(`registry: ${entries.length} components synced (${perCategory})`);
